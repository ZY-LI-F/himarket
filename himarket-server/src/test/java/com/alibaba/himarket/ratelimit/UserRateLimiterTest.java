package com.alibaba.himarket.ratelimit;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneOffset;
import org.junit.jupiter.api.Test;

class UserRateLimiterTest {

    @Test
    void allowsOneRequestPerUserEveryFiveSeconds() {
        MutableClock clock = new MutableClock(Instant.parse("2026-05-06T00:00:00Z"));
        UserRateLimiter limiter = new UserRateLimiter(clock, Duration.ofSeconds(5));

        assertTrue(limiter.tryAcquire("user-a"));
        assertFalse(limiter.tryAcquire("user-a"));
        assertTrue(limiter.tryAcquire("user-b"));

        clock.advance(Duration.ofSeconds(5));

        assertTrue(limiter.tryAcquire("user-a"));
    }

    private static final class MutableClock extends Clock {

        private Instant instant;

        private MutableClock(Instant instant) {
            this.instant = instant;
        }

        private void advance(Duration duration) {
            instant = instant.plus(duration);
        }

        @Override
        public ZoneOffset getZone() {
            return ZoneOffset.UTC;
        }

        @Override
        public Clock withZone(java.time.ZoneId zone) {
            return Clock.fixed(instant, zone);
        }

        @Override
        public Instant instant() {
            return instant;
        }
    }
}
